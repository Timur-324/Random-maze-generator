"""События пошаговой генерации и поиска.

Генераторы и решатели работают как ленивые потоки событий. GUI рисует
ровно то, что приходит в потоке, а CLI и тесты просто прогоняют поток
до конца, ничего не отрисовывая. Так визуализация не влияет на логику.

Виды событий:

* ``VISIT``    — клетка добавлена в лабиринт (впервые достигнута);
* ``CARVE``    — пробита стена между клетками ``a`` и ``b``;
* ``FRONTIER`` — клетка попала в очередь/кучу (frontier, ещё не раскрыта);
* ``EXPAND``   — клетка извлечена из очереди/кучи и раскрыта (explored);
* ``FOUND``    — путь найден, ``a`` — клетка пути от старта к финишу.
"""

from collections import namedtuple

VISIT = "visit"
CARVE = "carve"
FRONTIER = "frontier"
EXPAND = "expand"
FOUND = "found"

Event = namedtuple("Event", "kind a b", defaults=(None,))
